// The wire between builds and its compatibility rule (P5 O1 M6, OX1; docs/doperpowers/plans/2026-10-27-p5-o1-seams.md).
// Two builds of one wire major interoperate. A change within the major is additive: a new command, a new event, or a
// new optional property of an object schema at any depth. Everything else takes a major: a removed command, event or
// property; a property made required or made optional; a changed type, `const`, `enum` or union member set (an added
// enum member included, since an older reader refuses it); a changed numeric, length or pattern bound; a changed
// `additionalProperties`; a changed owner. An additive change bumps WIRE_MINOR, so a peer can tell what the other knows;
// an optional behaviour a peer of the same major may lack is a capability, `<area>.<feature>`, and adding one is a minor
// change too.
//
// The manifest (wire-manifest.json, generated by `pnpm wire:manifest`, held by wire.test.ts) records the wire at the
// latest minor: every command owned by `engine-host` or `machine` (input and output), every event in HOST_EVENTS, C1's
// envelope and the socket layer's own messages. The pty host is always the app's own build and stays out, as does
// main-to-renderer traffic. A namespace O3 retags `machine` joins it as added commands.
//
// Later hellos (RL2, the hub's; O10 and O11) build on `classifyWireChange`'s rule.
import * as z from 'zod';
import {
  SOCKET_PROTOCOL,
  ClientExitSchema,
  ClientHelloSchema,
  ClientHelloV2Schema,
  DocumentsClosedSchema,
  DocumentsCloseSchema,
  DocumentsOpenSchema,
  ServerRefuseSchema,
  ServerWelcomeSchema,
  ServerWelcomeV2Schema,
} from '../host/socket-protocol';
import { HostClientGoneSchema, HostDocSchema, HostEventSchema, HostReadySchema, HostRequestSchema, HostResponseSchema } from './host-protocol';
import type { WireRegistry } from './registry';

export const WIRE_MAJOR: number = SOCKET_PROTOCOL;
export const WIRE_MINOR: number = 0;
export const WIRE_CAPABILITIES: readonly string[] = [];

// What a peer said of itself at the handshake.
export interface WirePeer {
  major: number;
  minor: number;
  build: string;
  capabilities: readonly string[];
}

// `entries` maps `commands.<name>` to `{ owner, input, output }` and `events.<name>`, `envelope.<t>` and
// `socket.<message>` to a JSON Schema, each as `z.toJSONSchema(schema, { unrepresentable: 'any' })` renders it (the
// rendering the wire fingerprint uses).
export interface WireManifest {
  major: number;
  minor: number;
  entries: Record<string, unknown>;
}

const jsonSchema = (schema: z.ZodType): unknown => z.toJSONSchema(schema, { unrepresentable: 'any' });

const OWNERS_ON_THE_WIRE = new Set(['engine-host', 'machine']);

// The envelope and socket messages are this module's own, the same for any registry.
const ENVELOPE: Record<string, z.ZodType> = {
  req: HostRequestSchema,
  res: HostResponseSchema,
  evt: HostEventSchema,
  ready: HostReadySchema,
  doc: HostDocSchema,
  clientGone: HostClientGoneSchema,
};
const SOCKET: Record<string, z.ZodType> = {
  hello: ClientHelloSchema,
  welcome: ServerWelcomeSchema,
  refuse: ServerRefuseSchema,
  exit: ClientExitSchema,
  'documents.open': DocumentsOpenSchema,
  'documents.close': DocumentsCloseSchema,
  'documents.closed': DocumentsClosedSchema,
  // the protocol-2 window's form, frozen until major 4 removes it: a change to it would strand a pre-O1 supervisor
  'v2.hello': ClientHelloV2Schema,
  'v2.welcome': ServerWelcomeV2Schema,
};

export function wireManifestOf(registry: WireRegistry): WireManifest {
  const entries: Record<string, unknown> = {};
  for (const name of Object.keys(registry.commands).sort()) {
    const { owner, input, output } = registry.commands[name];
    if (OWNERS_ON_THE_WIRE.has(owner)) entries[`commands.${name}`] = { owner, input: jsonSchema(input), output: jsonSchema(output) };
  }
  for (const name of [...registry.hostEvents].sort()) entries[`events.${name}`] = jsonSchema(registry.events[name]);
  for (const [t, schema] of Object.entries(ENVELOPE)) entries[`envelope.${t}`] = jsonSchema(schema);
  for (const [t, schema] of Object.entries(SOCKET)) entries[`socket.${t}`] = jsonSchema(schema);
  return { major: WIRE_MAJOR, minor: WIRE_MINOR, entries: Object.fromEntries(Object.entries(entries).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) };
}

// Each change from `previous` to `current` as a path, e.g. `commands.session.status.output.properties.foo`. Annotation
// keywords (a description, a title) are neither: a manifest that differs in nothing else differs only in rendering.
export function classifyWireChange(previous: WireManifest, current: WireManifest): { additive: string[]; breaking: string[] } {
  const change: Change = { additive: [], breaking: [] };
  const names = new Set([...Object.keys(previous.entries), ...Object.keys(current.entries)]);
  for (const name of [...names].sort()) {
    const was = previous.entries[name];
    const now = current.entries[name];
    if (was === undefined) change.additive.push(name);
    else if (now === undefined) change.breaking.push(name);
    else if (name.startsWith('commands.')) {
      const [a, b] = [was as CommandEntry, now as CommandEntry];
      if (a.owner !== b.owner) change.breaking.push(`${name}.owner`);
      diffSchema(a.input, b.input, `${name}.input`, change);
      diffSchema(a.output, b.output, `${name}.output`, change);
    } else diffSchema(was, now, name, change);
  }
  return change;
}

interface Change {
  additive: string[];
  breaking: string[];
}
interface CommandEntry {
  owner: string;
  input: unknown;
  output: unknown;
}
type Schema = Record<string, unknown>;

const ANNOTATIONS = new Set(['description', 'title', 'examples', '$comment', 'deprecated']);
const SUBSCHEMA = new Set(['items', 'additionalProperties', 'propertyNames', 'not', 'contains', 'if', 'then', 'else', 'unevaluatedItems', 'unevaluatedProperties']);
const SUBSCHEMA_LISTS = new Set(['anyOf', 'oneOf', 'allOf', 'prefixItems']); // a changed length is a changed member set
const SUBSCHEMA_MAPS = new Set(['$defs', 'definitions', 'patternProperties', 'dependentSchemas']);

const isSchema = (value: unknown): value is Schema => typeof value === 'object' && value !== null && !Array.isArray(value);

function diffSchema(was: unknown, now: unknown, path: string, change: Change): void {
  if (equal(was, now)) return;
  if (!isSchema(was) || !isSchema(now)) return void change.breaking.push(path);
  const objects = isSchema(was.properties) && isSchema(now.properties);
  for (const key of new Set([...Object.keys(was), ...Object.keys(now)])) {
    if (ANNOTATIONS.has(key)) continue;
    const at = `${path}.${key}`;
    if (objects && key === 'properties') diffProperties(was, now, path, change);
    else if (objects && key === 'required') continue; // read per property, with `properties`
    else if (!(key in was) || !(key in now)) change.breaking.push(at);
    else if (SUBSCHEMA.has(key)) diffSchema(was[key], now[key], at, change);
    else if (SUBSCHEMA_LISTS.has(key)) {
      const [a, b] = [was[key], now[key]];
      if (!Array.isArray(a) || !Array.isArray(b) || a.length !== b.length) change.breaking.push(at);
      else a.forEach((member, i) => diffSchema(member, b[i], `${at}.${i}`, change));
    } else if (SUBSCHEMA_MAPS.has(key) && isSchema(was[key]) && isSchema(now[key])) {
      const [a, b] = [was[key] as Schema, now[key] as Schema];
      for (const name of new Set([...Object.keys(a), ...Object.keys(b)])) {
        if (!(name in a) || !(name in b)) change.breaking.push(`${at}.${name}`);
        else diffSchema(a[name], b[name], `${at}.${name}`, change);
      }
    } else if (!equal(was[key], now[key])) change.breaking.push(at);
  }
}

// An object schema's properties: a key added and not required is additive; one added required, removed, or made
// required or optional is breaking; a key on both sides is compared in depth.
function diffProperties(was: Schema, now: Schema, path: string, change: Change): void {
  const [a, b] = [was.properties as Schema, now.properties as Schema];
  const required = (schema: Schema) => new Set(Array.isArray(schema.required) ? (schema.required as string[]) : []);
  const [wasRequired, nowRequired] = [required(was), required(now)];
  for (const key of new Set([...Object.keys(a), ...Object.keys(b)])) {
    const at = `${path}.properties.${key}`;
    if (!(key in a)) (nowRequired.has(key) ? change.breaking : change.additive).push(at);
    else if (!(key in b)) change.breaking.push(at);
    else {
      if (wasRequired.has(key) !== nowRequired.has(key)) change.breaking.push(at);
      diffSchema(a[key], b[key], at, change);
    }
  }
}

function equal(a: unknown, b: unknown): boolean {
  if (a === b) return true;
  if (Array.isArray(a)) return Array.isArray(b) && a.length === b.length && a.every((item, i) => equal(item, b[i]));
  if (!isSchema(a) || !isSchema(b) || Array.isArray(b)) return false;
  const keys = Object.keys(a);
  return keys.length === Object.keys(b).length && keys.every((key) => key in b && equal(a[key], b[key]));
}
