export const REMOTE_EMPTIED_NAMES: ReadonlySet<string> = new Set([...B1O, ...U1O, ...UI.filter((name) => !J1O.has(name)), ...UKN].map((name) => name.toUpperCase()));

// A reference by the engine's own pattern (`:388404`): a letter or underscore, then letters, digits and underscores,
// then optionally `:-` and anything up to the brace.
const REFERENCE = /\$\{([A-Za-z_][A-Za-z0-9_]*)(?::-[^}]*)?\}/g;

const emptied = (name: string): boolean => {
  const upper = name.toUpperCase();
  const bare = upper.startsWith('INPUT_') ? upper.slice('INPUT_'.length) : upper;
  return REMOTE_EMPTIED_NAMES.has(bare) || bare.startsWith('OTEL_');
};

/** Each name of a `${NAME}` or `${NAME:-…}` in the text that the engine reads as empty toward a remote server: once, in
 * the order met, as the person wrote it. */
export function remoteEmptiedNamesIn(text: string): string[] {
  const found: string[] = [];
  for (const [, name] of text.matchAll(REFERENCE)) if (emptied(name) && !found.includes(name)) found.push(name);
  return found;
}
