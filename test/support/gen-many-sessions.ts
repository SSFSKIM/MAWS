// Writes test/fixtures/shell/many-sessions.json: three projects with 120 sessions each, for the sidebar's show-more and
// scale checks (C5 execution document, "Sidebar scale"). Deterministic: a seeded PRNG and a fixed clock, so the file is
// committed and regenerating it yields the same bytes. Run: node test/support/gen-many-sessions.ts
// Everything here is synthetic; the shapes follow nine-sessions.json, which is fixture-derived.
const fs = process.getBuiltinModule('node:fs');
const path = process.getBuiltinModule('node:path');

const SESSIONS_PER_PROJECT = 120;
const BASE_MS = Date.parse('2026-09-01T09:00:00.000Z');
const LOAD_MS = Date.parse('2026-09-28T10:10:00.000Z');

// mulberry32
let state = 0x5eed_c5;
function rand(): number {
  state = (state + 0x6d2b79f5) | 0;
  let t = state;
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
const pick = <T>(items: readonly T[]): T => items[Math.floor(rand() * items.length)];
const hex = (n: number): string => Array.from({ length: n }, () => Math.floor(rand() * 16).toString(16)).join('');
const uuid = (): string => `${hex(8)}-${hex(4)}-4${hex(3)}-${pick(['8', '9', 'a', 'b'])}${hex(3)}-${hex(12)}`;
const iso = (ms: number): string => new Date(ms).toISOString();

const VERBS = ['Fix', 'Refactor', 'Probe', 'Trace', 'Document', 'Speed up', 'Test', 'Review', 'Port', 'Untangle'];
const NOUNS = ['sidebar drag', 'quota countdown', 'trace stream', 'menu bar icon', 'settings migration', 'hook output', 'tab strip', 'journal replay', 'usage chart', 'reconnect loop', 'palette search', 'status line'];
const ACTIVITIES = ['Thinking', 'Running bun test', 'Editing src/app.ts', 'Reading README.md', 'Searching'];
const MODELS = [
  { requested: 'sonnet', resolved: 'claude-sonnet-5[1m]' },
  { requested: 'haiku', resolved: 'claude-haiku-4-5-20251001' },
];

const projects = [
  { id: 'proj-maws', name: 'MAWS', directory: '/Users/new/Developer/GitHub/MAWS' },
  { id: 'proj-codex-somersault', name: 'codex_somersault', directory: '/Users/new/Developer/GitHub/codex_somersault' },
  { id: 'proj-claude-usage-menubar', name: 'claude-usage-menubar', directory: '/Users/new/Developer/GitHub/claude-usage-menubar' },
].map((p, order) => ({ ...p, order, createdAt: iso(BASE_MS + order * 60_000) }));

const sessions: unknown[] = [];
const digests: unknown[] = [];
const engine: unknown[] = [];

projects.forEach((project, p) => {
  for (let i = 0; i < SESSIONS_PER_PROJECT; i++) {
    const engineSessionId = uuid();
    const appId = `app-${engineSessionId.slice(0, 8)}-${p}${String(i).padStart(3, '0')}`;
    const createdMs = BASE_MS + (p * SESSIONS_PER_PROJECT + i) * 97 * 60_000 + Math.floor(rand() * 60_000);
    const endedMs = createdMs + 60_000 + Math.floor(rand() * 40 * 60_000);
    // A light mix: most exited, a few idle or working with a live process, a few unread.
    const roll = rand();
    const phase = roll < 0.05 ? 'working' : roll < 0.12 ? 'idle' : 'exited';
    const live = phase !== 'exited';
    const unread = rand() < 0.1;
    const model = pick(MODELS);
    const routed = model.requested === 'sonnet';
    const mode = routed ? 'auto' : 'default';
    const totalUsd = Math.round(rand() * 400) / 100;
    const turnStartedMs = phase === 'working' ? LOAD_MS - Math.floor(rand() * 20 * 60_000) : endedMs - 30_000;
    sessions.push({
      appId, engineSessionId, projectId: project.id, directory: project.directory, additionalDirectories: [], worktree: null, branch: null,
      title: { text: `${pick(VERBS)} ${pick(NOUNS)} #${i + 1}`, source: 'user' },
      pinned: false, archived: false, holder: live ? { kind: 'self' } : { kind: 'none' },
      lastSeen: unread ? { messageUuid: null, at: null } : { messageUuid: null, at: iso(endedMs) },
      unread, engineVersion: '2.1.283', gateway: { routed }, model, effort: null,
      permissionMode: { requested: mode, effective: mode, refusal: null },
      createdAt: iso(createdMs), updatedAt: iso(endedMs),
    });
    digests.push({
      appSessionId: appId, phase, activity: phase === 'working' ? pick(ACTIVITIES) : null, lastAssistantLine: 'Done.',
      turnStartedAt: iso(turnStartedMs), lastTurnEndedAt: phase === 'working' ? null : iso(endedMs),
      context: null, cost: { totalUsd, sinceSeenUsd: unread ? totalUsd : 0 }, childAgents: { active: 0, done: 0 }, pendingRequests: 0,
    });
    if (live) {
      engine.push({
        appSessionId: appId, process: 'ready', engineState: phase === 'working' ? 'running' : 'idle',
        turn: phase === 'working' ? { origin: 'human', startedAt: iso(turnStartedMs), userMessageUuids: [] } : null, pendingRequests: 0,
      });
    }
  }
});

const scenario = {
  _synthetic: true,
  _note: 'Generated by test/support/gen-many-sessions.ts (seeded, deterministic); regenerate with node test/support/gen-many-sessions.ts.',
  version: 1, projects, sessions, digests, engine, attention: [], timeline: [],
};
const out = path.resolve(path.dirname(process.argv[1]), '../fixtures/shell/many-sessions.json');
fs.writeFileSync(out, `${JSON.stringify(scenario, null, 1)}\n`);
console.log(`wrote ${sessions.length} sessions to ${path.relative(process.cwd(), out)}`);
